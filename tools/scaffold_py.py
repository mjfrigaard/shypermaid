#!/usr/bin/env python3
"""Scaffold electron/ launcher for a Python package Shiny app.

Usage (from package root):
  python scaffold_py.py --strategy=bundled [--module=mypkg.app] [--attr=app] [--extras=shiny]
                        [--platforms=mac,win,linux] [--archs=x64,arm64] [--icon=path.png]
Re-run before every build: it refreshes the vendored package copy.
"""
import argparse, re, shutil, sys, tomllib
from pathlib import Path

VALID = ["shinylive", "bundled", "system", "auto-download", "container"]
ap = argparse.ArgumentParser()
ap.add_argument("--strategy", default="shinylive", choices=VALID)
ap.add_argument("--module"); ap.add_argument("--attr", default="app")
ap.add_argument("--platforms"); ap.add_argument("--archs"); ap.add_argument("--icon")
ap.add_argument("--extras", help="comma separated [project.optional-dependencies] groups to include")
a = ap.parse_args()

root = Path.cwd()
pp = root / "pyproject.toml"
if not pp.exists():
    sys.exit("Run from the package root (no pyproject.toml).")
proj = tomllib.loads(pp.read_text())["project"]
dist_name, version = proj["name"], proj.get("version", "0.0.0")
if "version" in proj.get("dynamic", []):
    print("! dynamic version: set app.version in _shinyelectron.yml manually")
import_name = re.sub(r"[-.]+", "_", dist_name).lower()

src = next((d for d in (root / "src" / import_name, root / import_name) if (d / "__init__.py").exists()), None)
if src is None:
    sys.exit(f"Cannot find package dir src/{import_name} or {import_name}/")
module = a.module or f"{import_name}.app"
mod_file = src.parent.joinpath(*module.split(".")).with_suffix(".py")
if mod_file.exists() and not re.search(rf"^{a.attr}\s*=", mod_file.read_text(), re.M):
    print(f"! {module} has no module-level `{a.attr} = App(...)`; expose one or pass --attr")

app_dir = root / "electron" / "app"
app_dir.mkdir(parents=True, exist_ok=True)

# Vendor a clean copy of the package (works for every strategy, no publishing needed)
dest = app_dir / import_name
shutil.rmtree(dest, ignore_errors=True)
shutil.copytree(src, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "tests"))
if any(dest.rglob("*.so")) or any(dest.rglob("*.pyd")) or any(src.rglob("*.pyx")):
    if a.strategy == "shinylive":
        sys.exit("Package has compiled extensions: shinylive/Pyodide cannot load them. Use a native strategy.")

(app_dir / "app.py").write_text(
    "# Generated launcher. Edit the package, not this file.\n"
    f"from {module} import {a.attr} as app  # noqa: F401\n"
)

deps = list(proj.get("dependencies", []))
optional = proj.get("optional-dependencies", {})
for group in (a.extras.split(",") if a.extras else []):
    if group not in optional:
        sys.exit(f"No [project.optional-dependencies] group named {group!r}")
    deps += [d for d in optional[group] if d not in deps]
if not any(re.match(r"shiny\b", d) for d in deps):
    deps.insert(0, "shiny")
(app_dir / "requirements.txt").write_text("\n".join(deps) + "\n")

def ylist(csv, ind): return [f"{' ' * ind}- {x}" for x in csv.split(",")] if csv else []
yml = ["# Generated by py-shinyelectron-pkg skill",
       "app:", f'  name: "{dist_name}"', f'  version: "{version}"',
       # Without a slug, shinyelectron names installers after the folder ("app-1.0.0...")
       f'  slug: "{re.sub(r"[^a-z0-9]+", "-", dist_name.lower()).strip("-")}"',
       "build:", '  type: "py-shiny"', f'  runtime_strategy: "{a.strategy}"']
if a.platforms: yml += ["  platforms:"] + ylist(a.platforms, 4)
if a.archs: yml += ["  architectures:"] + ylist(a.archs, 4)
if a.icon:
    shutil.copy(a.icon, app_dir / "icon.png"); yml.append('icon: "icon.png"')
rp = proj.get("requires-python", "any")
yml += ["dependencies:", "  auto_detect: true", "  python:",
        f"    version: null  # maintained pin; must satisfy requires-python {rp}. Exact pins like \"3.12.8\" allowed"]
(app_dir / "_shinyelectron.yml").write_text("\n".join(yml) + "\n")

(root / "electron" / "build.R").write_text(
    "# Build the desktop app. Run from the package root after scaffold_py.py.\n"
    "library(shinyelectron)\n"
    'app_check("electron/app")\n'
    "res <- export(\n"
    '  appdir    = "electron/app",\n'
    '  destdir   = "electron/dist",\n'
    "  overwrite = TRUE,\n"
    '  sign      = nzchar(Sys.getenv("CSC_LINK")),\n'
    "  run_after = interactive()\n"
    ")\nprint(res)\n")

gi = root / ".gitignore"
lines = gi.read_text().splitlines() if gi.exists() else []
for entry in ("electron/dist/", f"electron/app/{import_name}/"):
    if entry not in lines: lines.append(entry)
gi.write_text("\n".join(lines) + "\n")

print(f"Scaffolded electron/ for {dist_name} {version} ({a.strategy}).")
print("! Exclude electron/ from your sdist (e.g. [tool.hatch.build] exclude = [\"electron\"]).")
if a.strategy == "shinylive":
    print("! Every requirement must be pure Python or in Pyodide.")
